        <h1 id="introduction">Introduction</h1>
<p>REST API untuk aplikasi mobile SmartTrip Batam (Flutter) - autentikasi, katalog tempat, wishlist, generate itinerary otomatis, swap, live tracking, review, dan share trip.</p>
<aside>
    <strong>Base URL</strong>: <code>http://localhost:8000</code>
</aside>
<pre><code>Dokumentasi ini mencakup seluruh endpoint `/api/*` yang dikonsumsi mobile app SmartTrip Batam lewat Laravel Sanctum bearer token.

Panel admin (`/admin/*`, session auth `guard:web`, Laravel Blade + Bootstrap) sengaja **tidak** termasuk di sini - itu bukan REST API, cuma HTML form biasa buat kurasi data.

&lt;aside&gt;Klik endpoint mana pun di sebelah kiri untuk lihat detail parameter, contoh request, dan contoh response.&lt;/aside&gt;</code></pre>

        <h1 id="authenticating-requests">Authenticating requests</h1>
<p>To authenticate requests, include an <strong><code>Authorization</code></strong> header with the value <strong><code>"Bearer {YOUR_SANCTUM_TOKEN}"</code></strong>.</p>
<p>All authenticated endpoints are marked with a <code>requires authentication</code> badge in the documentation below.</p>
<p>Token didapat dari response <code>POST /auth/login</code>, <code>POST /auth/google</code>, atau setelah klik link verifikasi registrasi - berupa Sanctum personal access token (bukan JWT), dipakai sebagai <code>Authorization: Bearer {token}</code>.</p>

